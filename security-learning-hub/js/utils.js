/* 替换所有 data-icon 占位（幂等，可重复调用） */
function hydrateIcons(root=document){
  $$("[data-icon]", root).forEach(el => {
    el.innerHTML = iconSVG(el.dataset.icon, el.dataset.size||15);
  });
}
